type PromptCard = { key?: string; label: string; question: string; plannedValue: string | number; stake: string }

export function buildPrompt(card: PromptCard, a: string, b: string) {
  return `당신은 부부 재무설계 보조 도구입니다. 재무 조언은 하지 않습니다. 오직 세 가지만 판단합니다.

[설계 전제]
항목: ${card.label}
질문: ${card.question}
재무설계사가 설정한 전제: ${card.plannedValue}
이 전제가 흔들리면: ${card.stake}

[답변]
남편: ${a}
아내: ${b}

[판단 1·2] 각 답변이 전제와 얼마나 다른가 (aVsPlan, bVsPlan)
- "match": 전제와 같은 뜻. 표현만 다른 경우 포함 ("내년 봄" ≈ "2027년 3월" 처럼 시점이 겹치면 match).
- "minor": 전제와 방향은 같지만 정도·시점이 조금 다름. 또는 조건부/유보적 표현.
- "major": 전제와 다른 뜻이거나 반대 방향. 또는 전제 자체를 부정.
- 전제가 여러 항목으로 이루어져 있고 답변이 그중 일부만 말했다면, **말한 부분만** 보고 판단합니다.
  말하지 않은 항목은 부정한 것이 아닙니다.
- 전제에 **합의 사항**("~로 합의", "~하기로 함")이 있으면 그 합의가 기준입니다. 개인의 성향·선호 서술은
  합의를 설명하는 배경일 뿐이므로, 답변이 성향과는 맞아도 합의와 어긋나면 합의 기준으로 판단합니다.
- 구어체 완화 표현은 유보가 아닙니다. "한 1억 5천?", "1.5억 정도", "2029년쯤"은 그 값을 말한 것입니다 (match).
  유보는 "아직 모르겠다", "정해지지 않았다", "~일 수도 있다"처럼 **값 자체를 정하지 않은** 경우입니다.
- 부분적·시험적 제안("일부는 ~해도 될 것 같은데", "조금은 ~")은 전제를 뒤집은 것이 아니라
  흔들리는 것입니다 (minor). major 는 전제와 **다른 결정**을 이미 내렸거나 전제를 명시적으로 부정할 때입니다.

[판단 3] 두 답변이 서로 양립하는가 (abAgree)
- abAgree 는 "두 답변이 **동시에 참일 수 있는가**" 입니다. 같은 문장인지가 아닙니다.
- 서로 다른 부분을 말하는 것은 불일치가 **아닙니다**. 예: 한쪽은 "전세 때 8천 받았다",
  다른 쪽은 "매수 때 1.5억 받는다" → 둘 다 참일 수 있으므로 abAgree = true.
- 한쪽이 다른 쪽의 내용을 **부정·배제**할 때만 false 입니다. 예: "1.5억 받는다" vs "그건 빌리는 거다" → false.
- 한쪽이 "모르겠다"고만 했다면 부정이 아니므로 abAgree = true 로 둡니다.

[공통 지침]
- 확신이 없으면 minor 로 둡니다. 다른 뜻을 같다고 하는 것보다 같은 뜻을 다르다고 하는 편이 낫습니다
  (사용자가 이의 제기로 바로잡을 수 있음).
- 가치관·감정의 차이는 판단하지 않습니다. 사실·계획의 차이만 봅니다.
- 금액·기한을 계산하지 않습니다. 판정도 하지 않습니다. 위 세 값만 고릅니다.

반드시 아래 JSON만 출력하세요. 다른 텍스트 금지.
{"aVsPlan":"match|minor|major","bVsPlan":"match|minor|major","abAgree":true|false,"reason":"한국어 한 문장"}`
}

/**
 * 🔴 건의 설계사용 요약 (AI 활용 2번). 입력에 판정이 이미 들어 있다 — AI는 판정하지 않는다.
 * 조언·계산·질문 금지. 2줄(차이 · 함께 흔들리는 계획). 3줄째 검토 기준은 화면이 붙인다 (v4).
 */
export function buildSummaryPrompt(
  card: PromptCard,
  a: string,
  b: string,
  judgment: { verdict: string; redKind?: string; reason?: string; aVsPlan?: string; bVsPlan?: string },
) {
  // 11.05: 재무설계 결과와 다르면 다른 것 — 누가 다른지만 적는다 (부부 불일치 · 전제 폐기를 나누지 않는다)
  const who = [judgment.aVsPlan && judgment.aVsPlan !== 'match' ? '남편' : '', judgment.bVsPlan && judgment.bVsPlan !== 'match' ? '아내' : ''].filter(Boolean)
  const kind = judgment.redKind === 'repeated_yellow'
    ? '2회 연속 확인 필요 (같은 칸에서 확인 필요가 반복됨)'
    : judgment.verdict === 'red'
      ? `계획과 다름${who.length ? ` (${who.join(' · ')} 답이 계획과 다름)` : ''}`
      : '확인 필요 (답을 규칙으로 읽지 못함)'
  const related = (card.key ? REVIEW[card.key]?.related ?? [] : []).map(k => slotByKey(k)?.label).filter(Boolean).join(' · ')
  return `당신은 재무설계사의 보조 도구입니다. 아래 건을 설계사가 30초 안에 파악할 수 있게 2줄로 요약하세요.

[카드] ${card.label} — ${card.question}
[계획 (재무설계 결과)] ${card.plannedValue}
[이 계획이 바뀌면] ${card.stake}
[함께 다시 볼 질문] ${related || '없음'}
[남편 답변] ${a}
[아내 답변] ${b}
[판정] ${kind}${judgment.reason ? ` · ${judgment.reason}` : ''}

[규칙]
- 1줄: 계획과 두 분 답의 차이 — 누가 계획과 같고 누가 어떻게 다른지 (사실만)
- 2줄: 이 차이로 함께 흔들리는 계획 (위 '이 계획이 바뀌면'과 '함께 다시 볼 질문'만 근거로)
- 질문하지 않습니다. 물음표를 쓰지 않습니다. 재무설계 결과에 이미 있는 사실을 되묻지 않습니다.
- 금액·기한을 새로 계산하지 않습니다. 주어진 값만 인용합니다.
- 조언하지 않습니다 ("~하세요" 금지). 판정을 바꾸지 않습니다.
- 재무설계 결과의 값은 "계획"이라고 씁니다 ("전제"라고 쓰지 않습니다).
- 판정 내부 용어(match · minor · major 등 영어)를 쓰지 않습니다.
- 문장 끝은 "~함", "~음"으로 통일합니다 (예: "아내는 5억 5,000만 원으로 답함").
- 각 줄 50자 이내. 줄바꿈으로 구분. 다른 텍스트 없이 2줄만 출력하세요.`
}
